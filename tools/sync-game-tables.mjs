/**
 * The server's copy of the game tables.
 *
 *   node tools/sync-game-tables.mjs
 *
 * The slot machine's book and the roulette table live in src/data, where
 * the app reads them. The functions that decide a spin run on Deno and
 * cannot import the app's modules, so this writes them a TypeScript copy of
 * exactly the same numbers. Run it after touching either table; the
 * functions are wrong the moment the copies drift, and a test compares them.
 */
import { writeFileSync } from 'node:fs';
import { SYMBOLS, REEL, PAYLINES, PAYTABLE, LINE_BETS } from '../src/data/slots.js';
import { WHEEL_ORDER, TIER_BETS, CHIPS, TABLE_LIMIT, BETS } from '../src/data/roulette.js';
import { QUESTS, QUEST_TIERS, QUESTS_PER_DAY } from '../src/data/quests.js';

const head = '// Generated by tools/sync-game-tables.mjs from src/data. Do not edit by hand.\n';
writeFileSync('supabase/functions/_shared/slots.ts', head + `export const SYMBOL_IDS = ${JSON.stringify(SYMBOLS.map((s) => s.id))};
export const REEL: string[] = ${JSON.stringify(REEL)};
export const PAYLINES: { id: string; rows: number[] }[] = ${JSON.stringify(PAYLINES)};
export const PAYTABLE: Record<string, Record<number, number>> = ${JSON.stringify(PAYTABLE)};
export const LINE_BETS = ${JSON.stringify(LINE_BETS)};
`);
writeFileSync('supabase/functions/_shared/roulette.ts', head + `export const WHEEL_ORDER = ${JSON.stringify(WHEEL_ORDER)};
export const TIER_BETS: { id: string; numbers: number; multiplier: number }[] = ${JSON.stringify(TIER_BETS)};
export const CHIPS = ${JSON.stringify(CHIPS)};
export const TABLE_LIMIT = ${TABLE_LIMIT};
export const RETURNS: Record<string, number> = ${JSON.stringify(Object.fromEntries(Object.entries(BETS).filter(([, b]) => b.returns).map(([k, b]) => [k, b.returns])))};
`);
writeFileSync('supabase/functions/_shared/quests.ts', head + `export const QUESTS: { id: string; tier: string; target: number }[] = ${JSON.stringify(QUESTS.map((q) => ({ id: q.id, tier: q.tier, target: q.target })))};
export const TIER_WEIGHTS: Record<string, number> = ${JSON.stringify(Object.fromEntries(Object.entries(QUEST_TIERS).map(([k, v]) => [k, v.weight])))};
export const QUESTS_PER_DAY = ${QUESTS_PER_DAY};
`);
console.log('wrote supabase/functions/_shared/slots.ts, roulette.ts and quests.ts');
